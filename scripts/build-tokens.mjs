// build-tokens.mjs — generate src/styles/tokens.css from themes/*.tokens.json
//
// Variable naming (flatten nested keys to kebab-case, join with "-"):
//   color.surface.window        -> --adp-color-surface-window
//   color.surface.selectedRow   -> --adp-color-surface-selected-row
//   color.text.primary          -> --adp-color-text-primary
//   color.border.default        -> --adp-color-border-default
//   color.accent.excel          -> --adp-accent-excel        (accent shortcut, per spec)
//   color.accentDark.excel      -> --adp-accent-dark-excel
//   color.accentLight.excel     -> --adp-accent-light-excel
//   font.family                 -> --adp-font-family
//   font.size.body              -> --adp-font-body            (number gets a px suffix)
//   font.size.gallerySample     -> --adp-font-gallery-sample
//   radius.md                   -> --adp-radius-md            (number gets a px suffix)
//   shadow.page                 -> --adp-shadow-page          (string used verbatim)
//   space[i]                    -> --adp-space-<i>             (number gets a px suffix)
// Keys starting with "_" (e.g. "_source", "_derived") are notes and are skipped.
// Selectors: :root[data-theme="light"] and :root[data-theme="dark"].
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

function kebab(key) {
  return key
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .toLowerCase();
}

function isPxSection(path) {
  return (
    path[0] === "radius" ||
    path[0] === "space" ||
    (path[0] === "font" && path[1] === "size")
  );
}

function varName(path) {
  if (path[0] === "color" && path[1] === "accent") {
    return `--adp-accent-${kebab(path[2])}`;
  }
  if (path[0] === "color" && path[1] === "accentDark") {
    return `--adp-accent-dark-${kebab(path[2])}`;
  }
  if (path[0] === "color" && path[1] === "accentLight") {
    return `--adp-accent-light-${kebab(path[2])}`;
  }
  if (path[0] === "font" && path[1] === "size") {
    return `--adp-font-${kebab(path[2])}`;
  }
  if (path[0] === "space") {
    return `--adp-space-${path[1]}`;
  }
  return `--adp-${path.map(kebab).join("-")}`;
}

function flatten(value, path, out) {
  if (Array.isArray(value)) {
    value.forEach((item, index) => flatten(item, [...path, String(index)], out));
    return;
  }
  if (value !== null && typeof value === "object") {
    for (const [key, child] of Object.entries(value)) {
      if (key.startsWith("_")) continue;
      flatten(child, [...path, key], out);
    }
    return;
  }
  const rendered =
    typeof value === "number" && isPxSection(path) ? `${value}px` : String(value);
  out.push(`  ${varName(path)}: ${rendered};`);
}

function renderTheme(themeName, fileName) {
  const raw = readFileSync(join(root, "themes", fileName), "utf8").replace(/^\uFEFF/, "");
  const tokens = JSON.parse(raw);
  const lines = [];
  flatten(tokens, [], lines);
  lines.sort();
  return `:root[data-theme="${themeName}"] {\n${lines.join("\n")}\n}`;
}

const css = [
  "/* Generated by scripts/build-tokens.mjs from themes/*.tokens.json. Do not edit by hand. */",
  renderTheme("light", "light.tokens.json"),
  "",
  renderTheme("dark", "dark.tokens.json"),
  "",
].join("\n");

const outPath = join(root, "src", "styles", "tokens.css");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, css, "utf8");
console.log(`Wrote ${outPath}`);